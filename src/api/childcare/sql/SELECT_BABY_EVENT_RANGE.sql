WITH DATE_RANGE AS (
    SELECT %(START_DAY)s::DATE AS START_DAY, %(END_DAY)s::DATE AS END_DAY
)
SELECT BABY_EVENT.*
FROM BABY_EVENT
CROSS JOIN DATE_RANGE
WHERE BABY_ID=%(BABY_ID)s AND FAMILY_ID=%(FAMILY_ID)s
  AND (HAPPENED_AT AT TIME ZONE 'ASIA/TOKYO')::DATE >= START_DAY
  AND (HAPPENED_AT AT TIME ZONE 'ASIA/TOKYO')::DATE < END_DAY
ORDER BY HAPPENED_AT ASC, CREATED_AT ASC
