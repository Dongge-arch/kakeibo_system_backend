SELECT
    S.ID,
    S.SOURCE_TYPE,
    S.EXTERNAL_ID,
    S.TRANSACTION_DT,
    S.TRANSACTION_TM,
    S.MERCHANT_NAME,
    S.AMOUNT,
    S.CURRENCY,
    S.DIRECTION,
    S.SOURCE_KIND,
    S.ACCOUNT_LABEL,
    S.MATCH_STATUS,
    M.RET_ID,
    M.MATCH_SCORE,
    M.MATCH_TYPE,
    R.SUP_NAME,
    R.RET_DT,
    R.RET_TM,
    R.TOA_PRICE
FROM EXPENSE_SOURCE_TRANSACTION S
LEFT JOIN EXPENSE_SOURCE_MATCH M
    ON M.SOURCE_TRANSACTION_ID = S.ID
    AND M.DEL_FLAG = 0
LEFT JOIN RECEIPT_INFO R
    ON R.RET_ID = M.RET_ID
    AND R.CRE_USER_ID = S.CRE_USER_ID
    AND R.DEL_FLAG = 0
WHERE S.CRE_USER_ID = %(CRE_USER_ID)s
  AND S.DEL_FLAG = 0
ORDER BY S.TRANSACTION_DT DESC, COALESCE(S.TRANSACTION_TM, '') DESC, S.ID DESC;
