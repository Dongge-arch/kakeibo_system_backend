CREATE TABLE IF NOT EXISTS EXPENSE_SOURCE_TRANSACTION (
    ID BIGSERIAL PRIMARY KEY,
    CRE_PROG TEXT,
    UPD_PROG TEXT,
    SOURCE_TYPE TEXT NOT NULL,
    EXTERNAL_ID TEXT NOT NULL,
    TRANSACTION_DT TEXT NOT NULL,
    TRANSACTION_TM TEXT,
    MERCHANT_NAME TEXT,
    AMOUNT NUMERIC(100, 2) NOT NULL,
    CURRENCY TEXT DEFAULT 'JPY',
    DIRECTION TEXT DEFAULT 'DEBIT',
    SOURCE_KIND TEXT DEFAULT 'PAYMENT',
    ACCOUNT_LABEL TEXT,
    MATCH_STATUS TEXT DEFAULT 'UNMATCHED',
    RAW_DATA_JSON TEXT,
    CRE_DT TEXT,
    CRE_TM TEXT,
    UPD_DT TEXT,
    UPD_TM TEXT,
    CRE_USER_ID TEXT NOT NULL,
    UPD_USER_ID TEXT,
    DEL_FLAG INTEGER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (CRE_USER_ID, SOURCE_TYPE, EXTERNAL_ID)
);

CREATE TABLE IF NOT EXISTS EXPENSE_SOURCE_MATCH (
    ID BIGSERIAL PRIMARY KEY,
    CRE_PROG TEXT,
    UPD_PROG TEXT,
    SOURCE_TRANSACTION_ID BIGINT NOT NULL,
    RET_ID TEXT NOT NULL,
    MATCH_SCORE NUMERIC(5, 2) DEFAULT 0,
    MATCH_TYPE TEXT NOT NULL,
    CRE_DT TEXT,
    CRE_TM TEXT,
    UPD_DT TEXT,
    UPD_TM TEXT,
    CRE_USER_ID TEXT NOT NULL,
    UPD_USER_ID TEXT,
    DEL_FLAG INTEGER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_EXPENSE_SOURCE_MATCH_SOURCE
    ON EXPENSE_SOURCE_MATCH (SOURCE_TRANSACTION_ID)
    WHERE DEL_FLAG = 0;

CREATE INDEX IF NOT EXISTS IX_EXPENSE_SOURCE_TRANSACTION_USER_DATE
    ON EXPENSE_SOURCE_TRANSACTION (CRE_USER_ID, TRANSACTION_DT DESC)
    WHERE DEL_FLAG = 0;

CREATE TABLE IF NOT EXISTS AUTO_LINKAGE_SERVER_JOB (
    ID BIGSERIAL PRIMARY KEY,
    CRE_PROG TEXT,
    UPD_PROG TEXT,
    CONNECTION_TYPE TEXT NOT NULL,
    ACTION TEXT DEFAULT 'start',
    REQUEST_JSON TEXT,
    STATUS TEXT DEFAULT 'PENDING',
    RESULT_JSON TEXT,
    ERROR_MESSAGE TEXT,
    CRE_DT TEXT,
    CRE_TM TEXT,
    UPD_DT TEXT,
    UPD_TM TEXT,
    CRE_USER_ID TEXT NOT NULL,
    UPD_USER_ID TEXT,
    DEL_FLAG INTEGER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IX_AUTO_LINKAGE_SERVER_JOB_STATUS
    ON AUTO_LINKAGE_SERVER_JOB (STATUS, CREATED_AT)
    WHERE DEL_FLAG = 0;

CREATE TABLE IF NOT EXISTS GMAIL_OAUTH_TOKEN (
    ID BIGSERIAL PRIMARY KEY,
    CRE_PROG TEXT,
    UPD_PROG TEXT,
    EMAIL_ADDRESS TEXT,
    ACCESS_TOKEN TEXT,
    REFRESH_TOKEN TEXT,
    TOKEN_EXPIRES_AT TEXT,
    OAUTH_STATE TEXT,
    OAUTH_STATE_EXPIRES_AT TEXT,
    SCOPES TEXT,
    CRE_DT TEXT,
    CRE_TM TEXT,
    UPD_DT TEXT,
    UPD_TM TEXT,
    CRE_USER_ID TEXT NOT NULL,
    UPD_USER_ID TEXT,
    DEL_FLAG INTEGER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_GMAIL_OAUTH_TOKEN_USER
    ON GMAIL_OAUTH_TOKEN (CRE_USER_ID)
    WHERE DEL_FLAG = 0;
