SELECT
    R.RET_ID,
    R.SUP_NAME,
    R.RET_DT,
    R.RET_TM,
    R.TOA_PRICE
FROM RECEIPT_INFO R
WHERE R.CRE_USER_ID = %(CRE_USER_ID)s
  AND R.DEL_FLAG = 0
  AND NOT EXISTS (
      SELECT 1
      FROM EXPENSE_SOURCE_MATCH M
      WHERE M.RET_ID = R.RET_ID
        AND M.CRE_USER_ID = R.CRE_USER_ID
        AND M.DEL_FLAG = 0
  )
ORDER BY R.RET_DT DESC, R.RET_TM DESC;
